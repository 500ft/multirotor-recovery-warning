function make_results_tables(root, tableDir)
%MAKE_RESULTS_TABLES Write the calculated tables of Analysis/current-results.md as LaTeX.
%   booktabs rules and siunitx columns; every number is read from a committed JSON file:
%   Data/figure-data/current-results-tables.json (python -m Analysis.export_results_tables),
%   Data/release_recovery_results.json and Data/monte_carlo_results.json.
%   Output: <tableDir>/<name>.tex tabular fragments, typeset by typeset_tables.py.

X = jsondecode(fileread(fullfile(root, 'Data', 'figure-data', 'current-results-tables.json')));
R = jsondecode(fileread(fullfile(root, 'Data', 'release_recovery_results.json')));
MC = jsondecode(fileread(fullfile(root, 'Data', 'monte_carlo_results.json')));
src = @(f) sprintf(['%% Generated by Analysis/matlab/make_results_tables.m from %s; do not edit by hand.\n' ...
    '\\sisetup{per-mode=symbol}'], f);
cur = 'Data/figure-data/current-results-tables.json';

% ---- mass budget ----------------------------------------------------------------
m = X.mass_budget;
L = {src(cur)
     '\begin{tabular}{@{}l S[table-format=3.2]@{}}'
     '\toprule'
     'Quantity & {Mass (\unit{\gram})} \\'
     '\midrule'
     sprintf('Best case & %.2f \\\\', m.best_g)
     sprintf('Nominal & %.2f \\\\', m.nominal_g)
     sprintf('Worst case & %.2f \\\\', m.worst_g)
     sprintf('Unmodeled-hardware allowance & %.2f \\\\', m.unmodeled_hardware_g)
     sprintf('Proposed frozen maximum & %.2f \\\\', m.proposed_frozen_max_g)
     sprintf('Nominal margin to proposed maximum & %.2f \\\\', m.nominal_margin_g)
     '\bottomrule'
     '\end{tabular}'};
put(tableDir, 'mass_budget', L);

% ---- first-order recovery envelope ----------------------------------------------
name = containers.Map({'best', 'nominal', 'worst', 'nominal_no_drag'}, ...
    {'Best placeholder case', 'Nominal placeholder case', 'Worst placeholder case', ...
     'Nominal no-drag bound'});
yn = {'No', 'Yes'};
rows = {};
for r = rows_of(X.recovery_envelope)
    rows{end + 1, 1} = sprintf('%s & %.2f & %.2f & %s \\\\', name(r.name), ...
        r.minimum_height_m, r.available_height_m, yn{r.testable_now + 1}); %#ok<AGROW>
end
L = [{src(cur)
      '\begin{tabular}{@{}l S[table-format=2.2] S[table-format=1.2] l@{}}'
      '\toprule'
      'Case & {Minimum height (\unit{\metre})} & {Available height (\unit{\metre})} & Testable now \\'
      '\midrule'}; rows; {'\bottomrule'; '\end{tabular}'}];
put(tableDir, 'recovery_envelope_first_order', L);

% ---- guard functional check -------------------------------------------------------
pf = {'Fail', 'Pass'};
rows = {};
for r = rows_of(X.guard_check)
    rows{end + 1, 1} = sprintf('%s & %.2f & %.2f & %.2f & %s \\\\', name(r.name), ...
        1000 * r.deflection_m, r.clearance_safety_factor, r.elastic_stress_safety_factor, ...
        pf{r.functional_pass + 1}); %#ok<AGROW>
end
L = [{src(cur)
      '\begin{tabular}{@{}l S[table-format=2.2] S[table-format=1.2] S[table-format=2.2] l@{}}'
      '\toprule'
      ' & & \multicolumn{2}{c}{Safety factor} & \\'
      '\cmidrule(lr){3-4}'
      'Case & {Predicted deflection (\unit{\milli\metre})} & {Clearance} & {Elastic stress} & Functional result \\'
      '\midrule'}; rows; {'\bottomrule'; '\end{tabular}'}];
put(tableDir, 'guard_check', L);

% ---- classifier confidence bounds -------------------------------------------------
rows = {};
for r = rows_of(X.classifier_bounds)
    rows{end + 1, 1} = sprintf('%d false positives in %s trials & %.3f \\\\', ...
        r.false_positives, thousands(r.trials), 100 * r.upper_bound_95); %#ok<AGROW>
end
L = [{src(cur)
      '\begin{tabular}{@{}l S[table-format=1.3]@{}}'
      '\toprule'
      'Observation & {Exact 95\,\% upper bound (\unit{\percent})} \\'
      '\midrule'}; rows; {'\bottomrule'; '\end{tabular}'}];
put(tableDir, 'classifier_bounds', L);

% ---- 6-DoF closed-loop envelope ------------------------------------------------------
edgeText = containers.Map({'gyro_limit', 'failure'}, ...
    {'Gyro limit: no failure up to the sensor range', 'Dynamic failure'});
rows = {};
for tier = {'best', 'nominal', 'worst'}
    s = R.envelope_by_tier.(tier{1});
    rows{end + 1, 1} = sprintf('%s & %.1f & %.0f & %s \\\\', [upper(tier{1}(1)) tier{1}(2:end)], ...
        s.max_recoverable_rate_rad_s, s.max_recoverable_rate_deg_s, edgeText(s.envelope_edge)); %#ok<AGROW>
end
L = [{src('Data/release_recovery_results.json')
      '\begin{tabular}{@{}l S[table-format=2.1] S[table-format=4.0] l@{}}'
      '\toprule'
      ' & \multicolumn{2}{c}{Highest recovered rate} & \\'
      '\cmidrule(lr){2-3}'
      'Tier & {(\unit{\radian\per\second})} & {(\unit{\degree\per\second})} & Envelope edge \\'
      '\midrule'}; rows; {'\bottomrule'; '\end{tabular}'}];
put(tableDir, 'closed_loop_envelope', L);

% ---- Monte Carlo dispersion sweep -------------------------------------------------------
sc = MC.scenarios;
if ~iscell(sc), sc = num2cell(sc); end
rateNames = fieldnames(sc{1}.by_rate);
rateVals = cellfun(@(f) str2double(strrep(strrep(f, 'x', ''), '_', '.')), rateNames);
head = strjoin(arrayfun(@(v) sprintf('{\\qty{%.1f}{\\radian\\per\\second}}', v), rateVals', ...
    'UniformOutput', false), ' & ');
cgLabel = {'As-toleranced', 'Balance-controlled'};
rows = {};
for k = 1:2
    cells = cellfun(@(f) mc_cell(sc{k}.by_rate.(f), false), rateNames', 'UniformOutput', false);
    rows{end + 1, 1} = sprintf('%s (CG offset $\\leq$ \\qty{%g}{\\milli\\metre}) & %s \\\\', ...
        cgLabel{k}, 1000 * sc{k}.dispersions.cg_offset_max_m, strjoin(cells, ' & ')); %#ok<AGROW>
end
L = [{src('Data/monte_carlo_results.json')
      '\begin{tabular}{@{}l r r r@{}}'
      '\toprule'
      ' & \multicolumn{3}{c}{Recovered / trials (success rate), by initial tumble rate} \\'
      '\cmidrule(l){2-4}'
      ['Scenario & ' head ' \\']
      '\midrule'}; rows; {'\bottomrule'; '\end{tabular}'}];
put(tableDir, 'monte_carlo_dispersion', L);

% ---- CG offset that uses the placeholder torque budget ---------------------------------
cg = MC.static_cg_tolerance;
keys = fieldnames(cg);
label = {'Hover', 'Recovery peak'};
rows = {};
for k = 1:numel(keys)
    thrust = str2double(regexprep(keys{k}, '^thrust_(\d+)_(\d+)N$', '$1.$2'));
    rows{end + 1, 1} = sprintf('%s (\\qty{%g}{\\newton}) & %.2f & %.2f \\\\', label{k}, thrust, ...
        cg.(keys{k}).cg_100pct_budget_mm, cg.(keys{k}).cg_50pct_margin_mm); %#ok<AGROW>
end
L = [{src('Data/monte_carlo_results.json')
      '\begin{tabular}{@{}l S[table-format=1.2] S[table-format=1.2]@{}}'
      '\toprule'
      ' & \multicolumn{2}{c}{CG offset (\unit{\milli\metre})} \\'
      '\cmidrule(l){2-3}'
      'Thrust condition & {100\,\% of budget} & {50\,\% margin} \\'
      '\midrule'}; rows; {'\bottomrule'; '\end{tabular}'}];
put(tableDir, 'cg_offset_budget', L);

% ---- scenario A against scenario C (mixer authority) --------------------------------------
a = sc{1}; c = sc{end};
cellsA = cellfun(@(f) mc_cell(a.by_rate.(f), false), rateNames', 'UniformOutput', false);
cellsC = cellfun(@(f) mc_cell(c.by_rate.(f), true), rateNames', 'UniformOutput', false);
L = {src('Data/monte_carlo_results.json')
     '\begin{tabular}{@{}l r r r@{}}'
     '\toprule'
     ' & \multicolumn{3}{c}{Recovered / trials (success rate; exact 95\,\% lower bound for C)} \\'
     '\cmidrule(l){2-4}'
     ['Scenario & ' head ' \\']
     '\midrule'
     ['A: placeholder authority & ' strjoin(cellsA, ' & ') ' \\']
     sprintf('C: mixer authority (assumed \\qty{%g}{\\milli\\metre} arm) & %s \\\\', ...
         1000 * c.dispersions.mixer_arm_m, strjoin(cellsC, ' & '))
     '\bottomrule'
     '\end{tabular}'};
put(tableDir, 'mixer_authority', L);
end

function out = rows_of(s)
% struct array or cell array from jsondecode -> 1xN struct array for a for-loop
if iscell(s), s = [s{:}]; end
out = reshape(s, 1, []);
end

function s = mc_cell(b, withLower)
s = sprintf('%d/%d (\\qty{%.1f}{\\percent}', b.successes, b.n, 100 * b.success_rate);
if withLower
    s = [s sprintf('; $\\geq$ \\qty{%.1f}{\\percent}', 100 * b.success_rate_95_lower)];
end
s = [s ')'];
end

function s = thousands(n)
s = regexprep(sprintf('%d', n), '(\d)(?=(\d{3})+$)', '$1,');
end

function put(tableDir, stem, L)
writelines(string(L), fullfile(tableDir, [stem '.tex']));
end
