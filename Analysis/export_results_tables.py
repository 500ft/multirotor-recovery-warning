"""Write the values behind the calculated tables in Analysis/current-results.md.

Run from the repo root:  python -m Analysis.export_results_tables
Output: Data/figure-data/current-results-tables.json

The mass budget, first-order recovery envelope, guard check and classifier bounds
are computed by their analysis scripts on demand and have no results file. This
script stores them unrounded, so Analysis/matlab/make_results_tables.m can write the
typeset tables without retyping a number. The 6-DoF and Monte Carlo tables read
Data/release_recovery_results.json and Data/monte_carlo_results.json directly.
"""
import json
from pathlib import Path

from Analysis import guard, recovery
from Analysis.budget import load_mass_budget, rollup
from Analysis.classifier_stats import zero_event_upper_bound

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Data" / "figure-data" / "current-results-tables.json"
CLASSIFIER_TRIALS = (300, 1000)


def tables() -> dict:
    mass = rollup(load_mass_budget())
    cases = recovery.default_cases()
    envelope = [recovery.evaluate_case(c) for c in cases]
    envelope.append(recovery.evaluate_case(recovery.no_drag(cases[1])))
    return {
        "note": "Generated by Analysis/export_results_tables.py; unrounded values.",
        "mass_budget": {k: mass[k] for k in ("best_g", "nominal_g", "worst_g",
                                             "unmodeled_hardware_g", "proposed_frozen_max_g",
                                             "nominal_margin_g", "below_abort_threshold")},
        "recovery_envelope": [{k: r[k] for k in ("name", "minimum_height_m",
                                                 "available_height_m", "testable_now")}
                              for r in envelope],
        "guard_check": [{k: r[k] for k in ("name", "deflection_m", "clearance_safety_factor",
                                           "elastic_stress_safety_factor", "functional_pass")}
                        for r in (guard.evaluate_guard(c) for c in guard.default_cases())],
        "classifier_bounds": [{"false_positives": 0, "trials": n,
                               "upper_bound_95": zero_event_upper_bound(n)}
                              for n in CLASSIFIER_TRIALS],
    }


def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(tables(), indent=2) + "\n")
    print(f"[written] {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
